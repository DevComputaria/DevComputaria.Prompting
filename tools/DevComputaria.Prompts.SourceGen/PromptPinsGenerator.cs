using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace DevComputaria.Prompts.SourceGen;

[Generator]
public sealed class PromptPinsGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var catalog = context.AdditionalTextsProvider
            .Where(file => Path.GetFileName(file.Path).Equals("catalog.yaml", StringComparison.OrdinalIgnoreCase))
            .Select((file, cancellationToken) => file.GetText(cancellationToken)?.ToString())
            .Where(text => text is not null);

        context.RegisterSourceOutput(catalog, static (productionContext, text) =>
            productionContext.AddSource("PromptPins.g.cs", SourceText.From(Generate(text!), Encoding.UTF8)));
    }

    private static string Generate(string catalog)
    {
        var pins = Parse(catalog);
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("namespace DevComputaria.Prompts.Ids;");
        builder.AppendLine();
        builder.AppendLine("public static class PromptPins");
        builder.AppendLine("{");

        foreach (var prompt in pins.GroupBy(pin => pin.Id, StringComparer.Ordinal).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            builder.Append("    public static class ").Append(ToIdentifier(prompt.Key)).AppendLine();
            builder.AppendLine("    {");
            foreach (var pin in prompt.OrderBy(pin => pin.Version, StringComparer.Ordinal))
            {
                builder.Append("        public static global::DevComputaria.PromptKit.Abstractions.PromptId V")
                    .Append(pin.Version.Replace('.', '_'))
                    .Append(" => new(\"").Append(Escape(pin.Id)).Append("\", \"")
                    .Append(Escape(pin.Version)).AppendLine("\");");
            }

            builder.AppendLine("    }");
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static IReadOnlyList<Pin> Parse(string catalog)
    {
        var result = new List<Pin>();
        string? currentId = null;
        var inPrompts = false;

        foreach (var rawLine in catalog.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None))
        {
            var trimmed = rawLine.Trim();
            if (trimmed == "prompts:")
            {
                inPrompts = true;
                continue;
            }

            if (trimmed == "skills:")
            {
                inPrompts = false;
                currentId = null;
                continue;
            }

            if (!inPrompts)
            {
                continue;
            }

            if (trimmed.StartsWith("- id:", StringComparison.Ordinal))
            {
                currentId = trimmed.Substring(5).Trim();
                continue;
            }

            if (currentId is null || !trimmed.StartsWith("versions:", StringComparison.Ordinal))
            {
                continue;
            }

            var versions = trimmed.Substring("versions:".Length).Trim().TrimStart('[').TrimEnd(']');
            foreach (var version in versions.Split(',').Select(value => value.Trim()).Where(value => value.Length > 0))
            {
                result.Add(new Pin(currentId, version));
            }
        }

        return result;
    }

    private static string ToIdentifier(string value)
        => string.Concat(value.Split(new[] { '.', '-', '_' }, StringSplitOptions.RemoveEmptyEntries)
            .Select(part => char.ToUpperInvariant(part[0]) + part.Substring(1)));

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private sealed class Pin
    {
        public Pin(string id, string version)
        {
            Id = id;
            Version = version;
        }

        public string Id { get; }

        public string Version { get; }
    }
}
